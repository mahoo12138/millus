/**
 * Unified Compiler Entry Point: IllustrationSpec + Theme -> Normalized SceneGraph
 * Includes Dynamic ViewBox Envelope Expansion so detour edges, self-loops, and outer labels
 * are never clipped by the SVG canvas boundary.
 */

import {
  coerceFiniteNumber,
  VALID_CANVAS_BACKGROUNDS,
  type BoundingBox,
  type IllustrationSpec,
  type ResolvedThemeTokens,
  type SceneEdge,
  type SceneGraph,
  type SceneNode,
} from "../schema/spec.ts";
import { TextMeasurer } from "../runtime/text-measurer.ts";
import { HybridLayoutSolver, type LayoutOptions } from "./layout-solver.ts";
import { routeConnections } from "./edge-router.ts";
import { buildFocusAdjacency } from "./adjacency-builder.ts";

function translateNodeTree(
  nodes: SceneNode[],
  dx: number,
  dy: number
): void {
  for (const n of nodes) {
    n.x += dx;
    n.y += dy;
    if (n.children.length > 0) {
      translateNodeTree(n.children, dx, dy);
    }
  }
}

function translateAnchorRegistry(
  registry: Record<string, BoundingBox>,
  dx: number,
  dy: number
): void {
  for (const box of Object.values(registry)) {
    box.x += dx;
    box.y += dy;
  }
}

/**
 * Translates an absolute-coordinate SVG path string (M/L/Q/C commands generated by edge-router)
 * by (dx, dy) in O(length), avoiding an expensive second routing pass.
 */
function translateAbsolutePathD(pathD: string, dx: number, dy: number): string {
  if (!pathD || (dx === 0 && dy === 0)) return pathD;
  return pathD.replace(
    /(-?\d+(?:\.\d+)?)\s+(-?\d+(?:\.\d+)?)/g,
    (_match, rawX: string, rawY: string) => {
      const nx = parseFloat(rawX) + dx;
      const ny = parseFloat(rawY) + dy;
      const fx = rawX.includes(".") ? nx.toFixed(1) : String(Math.round(nx));
      const fy = rawY.includes(".") ? ny.toFixed(1) : String(Math.round(ny));
      return `${fx} ${fy}`;
    }
  );
}

function translateEdges(edges: SceneEdge[], dx: number, dy: number): void {
  for (const edge of edges) {
    for (const pt of edge.points) {
      pt[0] += dx;
      pt[1] += dy;
    }
    if (edge.labelBox) {
      edge.labelBox.x += dx;
      edge.labelBox.y += dy;
    }
    edge.pathD = translateAbsolutePathD(edge.pathD, dx, dy);
  }
}

function measureEdgesEnvelope(edges: SceneEdge[]): {
  minX: number;
  minY: number;
  maxX: number;
  maxY: number;
} {
  let minX = Infinity;
  let minY = Infinity;
  let maxX = -Infinity;
  let maxY = -Infinity;

  for (const edge of edges) {
    for (const pt of edge.points) {
      minX = Math.min(minX, pt[0]);
      minY = Math.min(minY, pt[1]);
      maxX = Math.max(maxX, pt[0]);
      maxY = Math.max(maxY, pt[1]);
    }
    if (edge.labelBox) {
      minX = Math.min(minX, edge.labelBox.x);
      minY = Math.min(minY, edge.labelBox.y);
      maxX = Math.max(maxX, edge.labelBox.x + edge.labelBox.width);
      maxY = Math.max(maxY, edge.labelBox.y + edge.labelBox.height);
    }
  }

  return { minX, minY, maxX, maxY };
}

export function compileIllustration(
  spec: IllustrationSpec,
  theme: ResolvedThemeTokens,
  options: LayoutOptions = {},
  measurer = new TextMeasurer()
): SceneGraph {
  const compact = options.compactViewport ?? false;
  const layoutSolver = new HybridLayoutSolver(measurer, theme);
  const layoutResult = layoutSolver.solve(spec, options);

  let edges = routeConnections(
    spec.connections,
    layoutResult.anchorRegistry,
    theme,
    measurer,
    compact
  );

  let finalWidth = layoutResult.width;
  let finalHeight = layoutResult.height;

  if (edges.length > 0) {
    const minMargin = 20;
    let env = measureEdgesEnvelope(edges);

    const shiftX =
      Number.isFinite(env.minX) && env.minX < minMargin
        ? Math.ceil(minMargin - env.minX)
        : 0;
    const shiftY =
      Number.isFinite(env.minY) && env.minY < minMargin
        ? Math.ceil(minMargin - env.minY)
        : 0;

    if (shiftX > 0 || shiftY > 0) {
      translateNodeTree(layoutResult.nodes, shiftX, shiftY);
      translateAnchorRegistry(layoutResult.anchorRegistry, shiftX, shiftY);
      translateEdges(edges, shiftX, shiftY);
      finalWidth += shiftX;
      finalHeight += shiftY;
      env = {
        minX: env.minX + shiftX,
        minY: env.minY + shiftY,
        maxX: env.maxX + shiftX,
        maxY: env.maxY + shiftY,
      };
    }

    const explicitCanvasW = coerceFiniteNumber(spec.canvas?.width);
    const explicitCanvasH = coerceFiniteNumber(spec.canvas?.height);
    if (explicitCanvasW === undefined && Number.isFinite(env.maxX)) {
      finalWidth = Math.max(finalWidth, Math.ceil(env.maxX + minMargin));
    }
    if (explicitCanvasH === undefined && Number.isFinite(env.maxY)) {
      finalHeight = Math.max(finalHeight, Math.ceil(env.maxY + minMargin));
    }
  }

  const adjacency = buildFocusAdjacency(layoutResult.nodes, edges);
  const rawBg = spec.canvas?.background;
  const background =
    rawBg && VALID_CANVAS_BACKGROUNDS.has(rawBg) ? rawBg : "dots";

  return {
    title: spec.title,
    width: finalWidth,
    height: finalHeight,
    viewBox: [0, 0, finalWidth, finalHeight],
    background,
    preset: theme.geometry.preset,
    theme,
    anchorRegistry: layoutResult.anchorRegistry,
    nodes: layoutResult.nodes,
    edges,
    adjacency,
  };
}
